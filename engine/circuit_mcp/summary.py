"""README sections that can be computed, so the agent writes only judgement.

Everything between BEGIN and END is regenerated on each call; everything
outside it (what the board does, design notes) belongs to the agent and is
never touched.
"""
import json
import pathlib

from circuit_mcp import checks, kicad, kicad_lib, partspec, paths, schematic, tools

BEGIN = "<!-- circuit:summary begin (generated by summarize_project; edits here are replaced) -->"
END = "<!-- circuit:summary end -->"

# The README's first line of prose until the agent writes what the board does;
# check_done treats it still being there as not done.
PLACEHOLDER = "_Describe what this board does._"


def default_board(source: pathlib.Path) -> str | None:
    """The board a netlist lays out when none is named: `<stem>.kicad_pcb`
    in the workspace, if it exists."""
    candidate = f"{source.stem}.kicad_pcb"
    return candidate if (paths.WORKSPACE / candidate).is_file() else None


def _esc(value) -> str:
    """A value bound for a Markdown table cell, with `|` escaped.

    Defence in depth: a net or part named with a literal `|` (unusual, and
    nothing here forbids it) would otherwise split its own table row.
    """
    return str(value).replace("|", "\\|")


def _parts(netlist_text: str) -> list[str]:
    rows = ["## Parts", "", "| Ref | Value | Footprint |", "|---|---|---|"]
    for ref, comp in sorted(kicad_lib.read_components(netlist_text).items()):
        rows.append(f"| {_esc(ref)} | {_esc(comp.value)} | {_esc(comp.footprint)} |")
    return rows


def _classes(netlist: pathlib.Path) -> tuple[list[str], list[str], int]:
    """`(net-classes rows, review rows, flagged-net count)`.

    The flagged count is returned explicitly rather than rebuilt from the
    shape of `review` -- `len(review) - 2` reads as 1 when nothing is
    flagged ("## Nets awaiting your decision", "", "None." is 3 items) and as
    -2 when there is no netclasses file yet (review is []), neither of which
    is the count of flagged nets.
    """
    # Beside the netlist, which is where set_net_classes writes it.
    path = netlist.with_suffix(".netclasses.json")
    if not path.is_file():
        return (["## Net classes", "", "Not classified: run `net_evidence` and `set_net_classes` before `run_layout`."], [], 0)
    spec = json.loads(path.read_text())
    # What run_layout actually routed each net at, after the pad cap.
    applied_file = path.with_suffix(".applied.json")
    applied = json.loads(applied_file.read_text()) if applied_file.is_file() else {}
    rows = ["## Net classes", "", "| Net | Class | Tier | Width (mm) | Source | Status |", "|---|---|---|---|---|---|"]
    flagged = [f"- **{f['net']}**: {f['reason']}" for f in spec.get("needs_review", [])]
    for net, e in sorted(spec.get("nets", {}).items()):
        width = applied.get(net, e["width_mm"])
        rows.append(f"| {_esc(net)} | {_esc(e.get('class', '-'))} | {_esc(e.get('tier') or '-')} | {_esc(width)} "
                    f"| {_esc(e.get('source', '-'))} | {_esc(e.get('status', '-'))} |")
        power = str(e.get("class", "")).startswith("power") or e.get("class") == "ground"
        if power and width < e["width_mm"]:
            flagged.append(f"- **{net}**: routed at {width:g} mm, pad-limited, "
                           f"below the {e['width_mm']:g} mm tier")
    review = ["## Nets awaiting your decision", ""]
    review += flagged or ["None."]
    return rows, review, len(flagged)


def _board_path(board: str | None) -> tuple[pathlib.Path | None, str | None]:
    """`(the board's path, None)`, or `(None, why there is no board to read)`."""
    if not board:
        return None, "No board yet: run `run_layout`."
    try:
        path = paths.inside(board)
    except ValueError as error:
        return None, f"{board}: {error}"
    if not path.is_file():
        return None, "No board yet: run `run_layout`."
    return path, None


def _status(board: str | None) -> str:
    """The one line that says whether the board is done."""
    path, _ = _board_path(board)
    if path is None:
        return "Status: NOT READY: no board yet"
    not_ready = tools.drc_status(path)
    return f"Status: NOT READY: {not_ready}" if not_ready else "Status: DRC clean"


def _schematic_line(stem: str) -> list[str]:
    sch, pdf, erc = schematic.files(stem)
    if not (paths.WORKSPACE / sch).is_file():
        # export_schematic's record that SKiDL can't draw this circuit
        # (final review, Critical 1): the README says so, and why.
        reason = schematic.unavailable_reason(paths.WORKSPACE / schematic.unavailable_file(stem))
        if reason is not None:
            return [f"Schematic: not available: {reason}.", ""]
        return ["Schematic: not generated: run `export_schematic`.", ""]
    try:
        erc_text = schematic.erc_summary(json.loads((paths.WORKSPACE / erc).read_text()))
    except (OSError, ValueError):
        erc_text = "ERC: no report"
    return [f"Schematic: {sch} (PDF: {pdf}); {erc_text}", ""]


def _board(board: str | None, status: str) -> list[str]:
    rows = ["## Board", "", status, ""]
    path, missing = _board_path(board)
    if path is None:
        return rows + [missing]
    info = kicad_lib.read_board(path.read_text(errors="replace"))
    rows.append(f"- File: `{board}`")
    rows.append(f"- Footprints: {info.footprints}")
    copper = ", ".join(f"{n} on {layer}" for layer, n in sorted(info.segments.items())) or "none"
    rows.append(f"- Track segments: {copper}")
    rows.append(f"- Outline ({kicad_lib.OUTLINE_LAYER}): "
                f"{'yes' if info.has_outline else 'NO -- the board has no edge'}")
    if not info.zones:
        rows.append("- Copper pours: none")
    elif info.unfilled:
        rows.append(f"- Copper pours: {info.zones}, {info.unfilled} NOT filled")
    else:
        rows.append(f"- Copper pours: {info.zones}, all filled")
    drc = paths.WORKSPACE / f"{pathlib.Path(board).stem}.drc.json"
    if drc.is_file():
        found = kicad.violations(json.loads(drc.read_text()))
        errors = [v for v in found if v.get("severity") == "error"]
        rows.append(f"- DRC: {len(errors)} error(s), {len(found) - len(errors)} warning(s)")
    gerbers = paths.WORKSPACE / "gerbers"
    if gerbers.is_dir():
        rows.append(f"- Gerbers: {', '.join(sorted(p.name for p in gerbers.iterdir()))}")
    return rows


def _board_checks(board: str | None, source: pathlib.Path) -> list[str]:
    """The routed board's per-net table and warnings (board-checks design)."""
    path, _ = _board_path(board)
    if path is None:
        return []
    try:
        facts, warned = checks.board_checks(path, source)
    except Exception:  # the README is written regardless
        return []
    return checks.readme_section(facts, warned) if facts else []


def _parts_awaiting(source: pathlib.Path) -> list[str]:
    """Parts make_part built for this board that no human has verified."""
    lines = partspec.awaiting(source.read_text(errors="replace"))
    return ["## Parts awaiting your verification", "",
            "Made from a datasheet; check each against it, then set `verified` in its spec.", "",
            *lines, ""] if lines else []


def summarize_project(netlist: str, board: str | None = None) -> str:
    try:
        source = paths.inside(netlist)
    except ValueError as error:
        return f"{netlist}: {error}"
    if not source.is_file():
        return f"no such netlist in the project: {netlist}"
    if board:
        try:
            paths.inside(board)
        except ValueError as error:
            return f"{board}: {error}"
    stem = source.stem
    board = board or default_board(source)
    classes, review, flagged_count = _classes(source)
    status = _status(board)
    block = "\n".join([BEGIN, *_parts(source.read_text(errors="replace")), "",
                       *classes, "", *review, "", *_parts_awaiting(source),
                       *_board_checks(board, source),
                       *_schematic_line(stem), *_board(board, status), END])
    readme = paths.WORKSPACE / "README.md"
    text = readme.read_text() if readme.is_file() else f"# {stem}\n\n{PLACEHOLDER}\n"

    begins, ends = text.count(BEGIN), text.count(END)
    # Splice only when the markers are exactly one well-formed pair, in
    # order. Anything else -- a stray BEGIN with no END, an END before a
    # BEGIN, two complete pairs -- is left untouched rather than guessed at:
    # str.split on a marker that is not there, or is there twice, either
    # raises (rest.split(END, 1)[1] on a missing END) or silently deletes
    # whatever text sits between the wrong pairing.
    if begins == 0 and ends == 0:
        text = text.rstrip() + "\n\n" + block + "\n"
    elif begins == 1 and ends == 1 and text.index(BEGIN) < text.index(END):
        head, rest = text.split(BEGIN, 1)
        text = head + block + rest.split(END, 1)[1]
    else:
        return (f"README.md has malformed circuit summary markers "
                f"({begins} begin, {ends} end); nothing was changed. Remove "
                f"the stray markers, then run summarize_project again.")
    readme.write_text(text)
    return (f"{status}\n"
            f"README.md updated: parts, net classes, {flagged_count} review line(s), board facts. "
            "Add what the board does and any design notes outside the generated block.")
